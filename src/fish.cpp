void drawFish(int x, int y){
    if(vx<=0){
        if(frame == 0){
            display.drawBitmap( x, y, epd_bitmap_fish1left, 16, 16, SSD1306_WHITE); //going left
        }
        else{
            display.drawBitmap( x, y, epd_bitmap_fish2left, 16, 16, SSD1306_WHITE); //left second frame
        }
        
    }
    else{
        if(frame == 0){
            display.drawBitmap( x, y, epd_bitmap_fish1right, 16, 16, SSD1306_WHITE); //going right
        }
        else{
            display.drawBitmap( x, y, epd_bitmap_fish2right, 16, 16, SSD1306_WHITE); //right second frame
        }
    }
    display.drawBitmap( 100, 34, epd_bitmap_spongebobPineapple, 32, 32, SSD1306_WHITE);
    display.drawBitmap( 10, 34, epd_bitmap_patrickRock, 32, 32, SSD1306_WHITE);
    display.drawBitmap( 55, 34, epd_bitmap_squidwardHouse, 32, 32, SSD1306_WHITE);
    // display.drawRect(fishX, fishY, 10, 10, SSD1306_WHITE);
}

void updateFish(){

    if(foodActive){
        if(foodX>fishX){
            vx=1;
        }
        else if(foodX<fishX){
            vx=-1;
        }
        else{
            vx=0;
        }

        if(foodY>fishY){
            vy=1;
        }
        else if(foodY<fishY){
            vy=-1;
        }
        else{
            vy=0;
        }

    }

    if(foodActive){
        if(abs(fishX - foodX) < 8 && abs(fishY - foodY) < 8){
            foodActive = false;
            vx = 0;
            vy = 0;
        }
}

    if(millis()-lastFrameTime > 300){ // animation frames of fish swimming
        if(frame ==0){
            frame = 1;
        }
        else{
            frame = 0;
        }
        lastFrameTime = millis();
    }

    fishX+=vx;
    fishY+=vy;

    if(fishX<=0 || fishX>=112){
        vx=-vx; // bounce off sides
    }
    if(fishY<=0 || fishY>=48){
        vy=-vy; // bounce off top and bottom
    }
    if(millis() - lastThink > random(2000,4000)){ //random thinking time
        lastThink=millis();

        vx = random(-1,2);
        vy = random(-1,2);
        
    }

}
void spawnFood(){
    foodActive=true;
    foodX=random(10,118);
    foodY=0;
}

void updateFood(){

    if(foodActive){
        foodY+=1;

        if(foodY>56){
            foodActive=false;
        }

    }
}

void drawFood(){
    if(foodActive){
        display.fillCircle(foodX, foodY, 2, SSD1306_WHITE);
    }
}

void showFish(){

    updateFish();
    updateFood();


    drawFish(fishX, fishY);
    drawFood();

    
}

